SET NOCOUNT ON;

SELECT
    REQ.CODREQ,
    REQ.CODFIL,
    REQ.DATATU,
    REQ.DATINC,
    LEFT(REQ.OBSERV, 35) AS OBSERV,
    REQ.CODFUN,
    FUN.NOMFUN,
    REQ.SITUAC,
    REQ.CODSET,
    SETOR.DESCRI AS DESCRI_SETOR,
    (
        SELECT TOP 1 IRQ.CODPROD
        FROM ESTIRQ AS IRQ WITH(NOLOCK)
        WHERE REQ.CODREQ = IRQ.CODREQ
    ) AS PRI_CODPRO
FROM ESTREQ AS REQ WITH(NOLOCK)
LEFT JOIN OSESET AS SETOR WITH(NOLOCK)
    ON REQ.CODSET = SETOR.CODSET
    AND SETOR.CODPAD IN (1)
    AND ISNULL(SETOR.INATIV, 'N') <> 'S'
LEFT JOIN OSEFUN AS FUN WITH(NOLOCK)
    ON REQ.CODFUN = FUN.CODFUN
    AND FUN.CODPAD IN (1)
    AND FUN.INAFUN = 'N'
WHERE REQ.DATATU >= DATEADD(month, -3, CAST(GETDATE() AS DATE))
ORDER BY
    CASE 
        WHEN REQ.SITUAC = 'P' THEN 1
        WHEN REQ.SITUAC = 'D' THEN 2
        ELSE 3
    END,
    REQ.CODREQ DESC;

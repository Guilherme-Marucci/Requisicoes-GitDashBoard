-- Consulta homologada de Itens de Pedidos vinculados a Requisições (últimos 3 meses)
-- Nota de esquema Rodopar: PK de ESTPED é NUMPED e PK de ESTIPE é ID_IPE (ESTIPE não possui coluna CODFIL; CODFIL pertence ao cabeçalho ESTPED).
SET NOCOUNT ON;

SELECT
    -- 1. Colunas prioritárias (início da visualização)
    ESTIPE.ID_IPE,
    ESTIPE.CODREQ,
    ESTIPE.NUMPED,
    ESTIPE.CODPROD,
    ESTIPE.QTDPED,
    ESTIPE.PREUNI,
    ESTIPE.PRETOT,

    -- 2. Demais colunas ativas da consulta original (ESTIPE)
    ESTIPE.QTDENT,
    ESTIPE.SITUAC,
    ESTIPE.DATATU,
    ESTIPE.USUATU,
    ESTIPE.DESCRI,
    ESTIPE.QTDCAN,
    ESTIPE.OBSERV,
    ESTIPE.CODCOT,
    ESTIPE.ICMSST,

    -- 3. Atributos complementares do Produto (ESTPRO)
    ESTPRO.UNIDAD,
    ESTPRO.REFERE,

    -- 4. Cabeçalho do Pedido (ESTPED) e Fornecedor (RODCLI) para DATINC/DATEMI, filial e consolidação
    ESTPED.CODFIL,
    ESTPED.DATINC,
    ESTPED.DATPED AS DATEMI,
    ESTPED.PREENT AS DATENT,
    ESTPED.SITUAC AS SITPED,
    ESTPED.VLRTOT AS VALTOT_PED,
    ESTPED.USUINC AS COMPRADOR,
    ESTPED.CODCLIFOR,
    COALESCE(NULLIF(LTRIM(RTRIM(RODCLI.NOMEAB)), ''), RODCLI.RAZSOC) AS FORNECEDOR,
    RODCLI.RAZSOC

FROM ESTIPE WITH (NOLOCK)
INNER JOIN ESTPED WITH (NOLOCK)
    ON ESTIPE.NUMPED = ESTPED.NUMPED
INNER JOIN ESTPRO WITH (NOLOCK)
    ON ESTIPE.CODPROD = ESTPRO.CODPROD
LEFT JOIN RODCLI WITH (NOLOCK)
    ON ESTPED.CODCLIFOR = RODCLI.CODCLIFOR

WHERE ESTIPE.NUMPED > 1
  AND ESTIPE.CODREQ IS NOT NULL
  AND ESTIPE.CODREQ > 0
  AND ESTIPE.DATATU >= DATEADD(MONTH, -3, CAST(GETDATE() AS DATE))

ORDER BY
    COALESCE(ESTPED.DATINC, ESTPED.DATPED, ESTIPE.DATATU) DESC,
    ESTIPE.NUMPED DESC,
    ESTIPE.ID_IPE DESC;
